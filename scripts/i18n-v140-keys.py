def add_keys(path, section, items):
    s = io.open(path, encoding="utf-8").read()
    m = re.search(rf'\n  {re.escape(section)}: \{{\n', s)
    assert m, f"section {section} missing in {path}"
    insert = m.end()
    add = "".join(f'    {k}: "{v}",\n' for k, v in items)
    s = s[:insert] + add + s[insert:]
    io.open(path, "w", encoding="utf-8").write(s)

fail = []
for lang, kv in K.items():
    path = f"{ROOT}/{lang}.ts"
    session = [(k.split(".", 1)[1], v) for k, v in kv.items() if k.startswith("session.")]
    bpop = [(k.split(".", 1)[1], v) for k, v in kv.items() if k.startswith("bpop.")]
    admin = [(k.split(".", 1)[1], v) for k, v in kv.items() if k.startswith("admin.")]
    try:
        add_keys(path, "session", session)
        # bpop: قسم جديد — أدرجه قبل قسم session
        s = io.open(path, encoding="utf-8").read()
        if "\n  bpop: {" not in s:
            m = re.search(r'\n  session: \{\n', s)
            block = "\n  bpop: {\n" + "".join(f'    {k}: "{v}",\n' for k, v in bpop) + "  },\n"
            s = s[:m.start()] + block + s[m.start():]
            io.open(path, "w", encoding="utf-8").write(s)
        add_keys(path, "admin", admin)
        print(lang, "OK")
    except Exception as e:
        fail.append((lang, str(e)))
        print(lang, "FAIL", e)
sys.exit(1 if fail else 0)
