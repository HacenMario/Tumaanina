def insert_section(src: str, lang: str) -> str:
    # 1) قبل نهاية القاموس النهائي — نجد آخر "}\n};\n" ثم ندرج القسم قبله
    # الملف ينتهي بـ "  },\n};" (قسم أخير) — إدراج قبل "};"
    idx = src.rstrip().rfind("};")
    assert idx > 0, "dict end not found"
    block = COURSES[lang]
    src = src[:idx] + block + src[idx:]
    return src

def insert_nav(src: str, lang: str) -> str:
    # بعد سطر clinicLogin
    m = re.search(r'\n(\s*)clinicLogin:\s*"[^"]*",', src)
    assert m, "clinicLogin anchor not found"
    ins = "\n" + m.group(1) + NAV[lang]
    return src[:m.end()] + ins + src[m.end():]

def insert_packopt(src: str, lang: str) -> str:
    m = re.search(r'\n(\s*)unpaidBadge:\s*"[^"]*",', src)
    assert m, "unpaidBadge anchor not found"
    ins = "\n" + m.group(1) + PACKOPT[lang]
    return src[:m.end()] + ins + src[m.end():]

for lang in ["ar", "en", "fr", "ru", "tr", "zh"]:
    p = BASE + f"{lang}.ts"
    s = open(p, encoding="utf-8").read()
    assert "courses: {" not in s, f"{lang} already has courses"
    s = insert_section(s, lang)
    s = insert_nav(s, lang)
    s = insert_packopt(s, lang)
    open(p, "w", encoding="utf-8").write(s)
    print(f"{lang}: OK")
